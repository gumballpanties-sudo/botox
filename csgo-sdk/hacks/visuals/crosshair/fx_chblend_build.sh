#!/usr/bin/env bash
# Rebuilds fx_chblend_ps.h (one ps_3_0 per crosshair blend mode) and fx_chblend_vs.h.
# Run from csgo-sdk/:  bash hacks/visuals/crosshair/fx_chblend_build.sh
# FXC=... overrides the compiler; otherwise the newest Windows Kits fxc is used.
set -euo pipefail

FIRST=2      # 0 normal / 1 additive never use a shader
LAST=121     # keep in step with kChBlend[] in ch_blend_modes.h

if [ -z "${FXC:-}" ]; then
    FXC=$(ls -d "/c/Program Files (x86)/Windows Kits/10/bin/"*/x64/fxc.exe 2>/dev/null | sort -V | tail -1)
fi
[ -x "$FXC" ] || { echo "fxc not found, set FXC="; exit 1; }

DIR=hacks/visuals/crosshair
TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT

"$FXC" //nologo //T vs_3_0 //E main //Fh "$DIR/fx_chblend_vs.h" //Vn k_fxChBlendVsBytes "$DIR/fx_chblend_vs.hlsl" >/dev/null

OUT="$TMP/ps.h"
{
    echo "// GENERATED by fx_chblend_build.sh from fx_chblend_ps.hlsl -- do not edit."
    echo "#pragma once"
} > "$OUT"
for ((m = FIRST; m <= LAST; m++)); do
    "$FXC" //nologo //T ps_3_0 //E main //D MODE=$m //Fh "$TMP/m$m.h" //Vn k_fxChBlendPs$m "$DIR/fx_chblend_ps.hlsl" >/dev/null \
        || { echo "mode $m failed"; exit 1; }
    cat "$TMP/m$m.h" >> "$OUT"
done
{
    echo ""
    echo "struct FxChBlendPs { const BYTE* bytes; unsigned size; };"
    echo "static const FxChBlendPs k_fxChBlendPs[] = {"
    for ((m = 0; m < FIRST; m++)); do echo "    { nullptr, 0 },"; done
    for ((m = FIRST; m <= LAST; m++)); do echo "    { k_fxChBlendPs$m, sizeof(k_fxChBlendPs$m) },"; done
    echo "};"
} >> "$OUT"
mv "$OUT" "$DIR/fx_chblend_ps.h"
echo "built modes $FIRST..$LAST"
